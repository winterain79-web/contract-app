export const fillNat = (text, nationality) => {
  const nat = (nationality || '').trim() || '○○';
  return String(text).replaceAll('{국적}', nat);
};

export const optionText = (optId, nationality) => {
  for (const list of Object.values(DUTY_OPTIONS)) {
    const hit = list.find(([id]) => id === optId);
    if (hit) return fillNat(hit[1], nationality);
  }
  return '';
};

