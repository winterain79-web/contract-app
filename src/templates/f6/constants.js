export const presetsFor = (applyType) => PRESETS.filter((p) => p.type === applyType);

export const fillPreset = (presetId, nationality) => {
  const p = PRESETS.find((x) => x.id === presetId);
  if (!p) return '';
  const nat = (nationality || '').trim() || '{국적}';
  return p.lines.map((l) => l.replaceAll('{국적}', nat)).join('\n');
};

